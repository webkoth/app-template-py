import { expect, test } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  // Минута на сценарий вместо штатных тридцати секунд. Оба теста ждут
  // ЧУЖОЙ процесс: воркер должен взять задачу из очереди, а экран — увидеть
  // результат следующим опросом. На своей машине это секунды, но бюджет
  // теста тратится не только на ожидание, и на загруженной машине конвейера
  // сценарий упирался бы в тридцать секунд целиком — отказ выглядел бы как
  // незавершённый разбор, хотя разбор просто не поместился в бюджет.
  // Проверено: с ожиданием в 30 секунд внутри 30-секундного теста наружу
  // выходит «Test timeout exceeded», то есть объявленное ожидание не
  // наступает никогда.
  test.setTimeout(60_000)

  await page.goto("/login")
  await page.getByLabel("Логин").fill("admin")
  await page.getByLabel("Пароль").fill("admin")
  await page.getByRole("button", { name: "Войти" }).click()
  // Клик по «Войти» только отправляет запрос. Без ожидания перехода
  // следующий page.goto уходит раньше, чем приходит кука сессии: гейт
  // возвращает на форму входа, и сценарий падает на поле «Файл», которого
  // там нет. Та же строка и по той же причине стоит в соседних спеках.
  await page.waitForURL("/")
})

// Имя файла уникально для прогона. База e2e между прогонами не чистится, и
// без метки времени строка второго прогона была бы неотличима от строки
// первого: strict mode Playwright упал бы на двух совпадениях, а проверка
// «задача дошла до готово» нашла бы прошлую задачу вместо этой — то есть
// осталась бы зелёной, даже если бы в этом прогоне не случилось ничего.
const unique = (prefix: string) => `${prefix}-${Date.now()}.csv`

test("таблица загружается, считается в фоне и показывает сводку", async ({
  page,
}) => {
  // Единственная проверка всей цепочки целиком: файл → очередь → воркер →
  // база → экран. Каждое звено закрыто своим тестом, но что они соединены
  // друг с другом, не проверяет ничто, кроме этого сценария.
  const name = unique("цены")

  await page.goto("/datasets")
  await page.getByLabel("Файл").setInputFiles({
    name,
    mimeType: "text/csv",
    buffer: Buffer.from("город,цена\nА,10\nБ,20\nА,30\n", "utf-8"),
  })

  // Ответ на загрузку ждётся вместе с кликом, а не после него: запрос
  // уходит и приходит быстрее, чем выполнится следующая строка.
  const [created] = await Promise.all([
    page.waitForResponse(
      (response) =>
        response.url().endsWith("/api/datasets") &&
        response.request().method() === "POST"
    ),
    page.getByRole("button", { name: "Загрузить" }).click(),
  ])

  // Что разбор ОТЛОЖЕН, проверяется здесь, а не бейджем «разбирается» на
  // экране. Бейдж — гонка с воркером, и тест её проигрывает случайно: между
  // ответом на загрузку и первым обновлением списка проходят десятки
  // миллисекунд, а воркер успевает разобрать три строки быстрее. Проиграв
  // гонку, сценарий краснел бы на исправной системе — то есть ровно тем
  // мигающим отказом, ради отсутствия которого он и написан.
  //
  // У ответа на POST такой гонки нет вовсе: сводку считает другой процесс,
  // которого в момент ответа ещё не звали, и `null` здесь не «пока не
  // посчитано», а «работа отложена». Сломай отложенность — разбирай прямо в
  // обработчике загрузки, — и эта строка покраснеет сразу.
  const uploaded: { summary: unknown } = await created.json()
  expect(uploaded.summary).toBeNull()

  // Фильтр по имени С РАСШИРЕНИЕМ: экран показывает original_name, а не
  // name — у второго бэкенд срезает расширение. Поменяешь колонку на name,
  // и фильтр перестанет находить строку.
  const row = page.getByRole("row").filter({ hasText: name })
  await expect(row).toBeVisible()

  // А через несколько секунд её считает воркер. Ожидание длинное намеренно:
  // экран опрашивает список раз в три секунды, и на медленной машине первое
  // обновление приходит не сразу.
  //
  // Ждём БЕЙДЖ, а не число строк. Первая редакция ждала текста «3» во всей
  // строке таблицы — и проходила мгновенно, ещё до разбора: имя файла
  // содержит Date.now(), а в нём почти всегда есть тройка. Проверка была
  // зелёной, ничего не дождавшись.
  //
  // Раньше времени бейдж не сойдётся: до разбора в ячейке стоит
  // «разбирается», при отказе — «не разобралась», и подстроки «разобрана»
  // нет ни в том, ни в другом.
  await expect(row).toContainText("разобрана", { timeout: 30_000 })
  // Число строк — в СВОЕЙ ячейке и точным совпадением, а не поиском «3» по
  // всей строке. Пока сводки нет, в этой ячейке прочерк; соседние ячейки
  // («38 Б», дата, имя файла) целиком тройке не равны никогда.
  await expect(row.getByRole("cell", { name: "3", exact: true })).toBeVisible()

  await row.click()
  // Подпись карточки. Она появляется, только когда сводка разобралась
  // схемой: пока сводки нет, карточка говорит «сводка считается», а при
  // отказе — «сводки нет».
  await expect(page.getByText("строк: 3")).toBeVisible()

  // «город» — текстовая колонка, и в выборе целевой её нет намеренно
  // (сервер отказывает по нечисловой цели, предлагать её значило бы
  // предлагать заведомый отказ). Здесь она ищется в СВОДКЕ, где есть все
  // колонки, а не в форме обучения.
  await expect(
    page.getByRole("row").filter({ hasText: "город" })
  ).toContainText("текст")

  // Сводку считал воркер по содержимому файла, а не экран по его имени:
  // среднее 20 из 10, 20 и 30 не написано нигде, кроме загруженных байтов.
  // Пока разбора не было, этой строки в сводке нет вовсе — сводки нет тоже.
  const price = page.getByRole("row").filter({ hasText: "цена" })
  await expect(price).toContainText("число")
  await expect(
    price.getByRole("cell", { name: "20", exact: true })
  ).toBeVisible()

  // Та же работа с другой стороны: разбор шёл ЧЕРЕЗ ОЧЕРЕДЬ, и задача о нём
  // видна на экране задач — под именем своей таблицы, а не идентификатором.
  // Гонки здесь нет: строка задачи остаётся в истории навсегда, а «готово»
  // к этому моменту уже проставлено — без него не появилась бы сводка,
  // которую проверки выше уже дождались.
  await page.goto("/jobs")
  const job = page.getByRole("row").filter({ hasText: name })
  await expect(job).toContainText("разбор таблицы")
  await expect(job).toContainText("готово")
})

test("таблица, которую не разобрать, называет причину", async ({ page }) => {
  // Обратная половина той же цепочки, и связана она отдельным звеном:
  // причина отказа живёт в ЗАДАЧЕ, а показывается на строке ТАБЛИЦЫ.
  // Разъедется это звено — таблица останется без сводки навсегда, и «идёт
  // счёт» будет неотличимо от «упало»: человек ждёт результата, которого не
  // будет.
  const name = unique("пустая")

  await page.goto("/datasets")
  await page.getByLabel("Файл").setInputFiles({
    name,
    mimeType: "text/csv",
    // Заголовок без единой строки. Загрузку такой файл проходит — это
    // настоящий CSV, — а отказывает на нём разбор: то есть отказ рождается
    // в ВОРКЕРЕ. Файл, отвергнутый самой загрузкой (скажем, PDF), проверял
    // бы совсем другое звено — ответ на запрос, а не фоновую работу.
    buffer: Buffer.from("город,цена\n", "utf-8"),
  })
  await page.getByRole("button", { name: "Загрузить" }).click()

  const row = page.getByRole("row").filter({ hasText: name })
  // Причина приходит не сразу и не с первой попытки: очередь возвращает
  // отказавшую задачу, пока попытки не исчерпаны, и до последней таблица
  // честно «разбирается».
  await expect(row).toContainText("не разобралась", { timeout: 30_000 })
  // Текст — от разбора, а не свой. Подменить его на «не удалось разобрать»
  // значило бы потерять ровно то, ради чего отказ и показывают.
  await expect(row).toContainText("В таблице нет строк")
})
