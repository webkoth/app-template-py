#!/usr/bin/env bash
#
# Ждёт прогон GitHub Actions ИМЕННО за этим коммитом и возвращает его код.
#
#   sh scripts/wait-for-run.sh ci.yml          # прогон ветки
#   sh scripts/wait-for-run.sh deploy.yml      # доставка
#   sh scripts/wait-for-run.sh deploy.yml <sha>
#
# Зачем отдельный скрипт вместо строчки в командах. Раньше все четыре места
# (`/ship` дважды, `/rollback`, установка) звали
#
#   gh run watch $(gh run list --branch main -L1 --json databaseId -q ...)
#
# и это тихо смотрело не туда. Между `git push` и появлением прогона есть
# окно в несколько секунд: `-L1` в этом окне отдаёт ПРОШЛЫЙ, уже завершённый
# прогон, `--exit-status` мгновенно возвращает 0, и агент объявляет доставку
# успешной — пока настоящая ещё идёт или уже падает. Если прогона нет вовсе,
# подстановка пуста, и команда падает невнятной жалобой самого `gh`.
#
# Отбор идёт по SHA коммита, а не по ветке: `--commit` сверяет `headSha`
# прогона, то есть выбирает ровно тот прогон, который запущен этим push.
# Имя конвейера тоже обязательно — на `main` их два (доставка и проверка
# свежести копий), и без него в ответе оказался бы любой из них.
#
# Ожидание, а не одна попытка: прогон появляется не мгновенно. Две минуты —
# запас на медленный ответ API; дольше ждать нечего, столько прогон не
# создаётся никогда, и молчаливое ожидание хуже внятного отказа.
set -eu

WORKFLOW=${1:-}
if [ -z "$WORKFLOW" ]; then
  echo "Нужно имя конвейера: sh scripts/wait-for-run.sh ci.yml|deploy.yml [sha]" >&2
  exit 2
fi
SHA=${2:-$(git rev-parse HEAD)}
ATTEMPTS=${WAIT_FOR_RUN_ATTEMPTS:-60}

RUN=""
i=0
while [ "$i" -lt "$ATTEMPTS" ]; do
  # `|| true`: пока прогона нет, gh отвечает пустым списком, а на сетевой
  # заминке — ненулевым кодом. Ни то, ни другое не повод бросать ожидание,
  # а `set -e` бросил бы.
  RUN=$(gh run list --workflow "$WORKFLOW" --commit "$SHA" -L1 \
    --json databaseId -q '.[0].databaseId' 2>/dev/null || true)
  [ -n "$RUN" ] && break
  i=$((i + 1))
  sleep 2
done

if [ -z "$RUN" ]; then
  echo "Прогон $WORKFLOW за коммит $(echo "$SHA" | cut -c1-7) так и не появился." >&2
  echo "Значит, его нет: проверь, что push прошёл и конвейер включён —" >&2
  echo "  gh run list -L5" >&2
  echo "Считать доставку успешной на этом основании нельзя." >&2
  exit 1
fi

echo "Прогон $RUN ($WORKFLOW за $(echo "$SHA" | cut -c1-7)), жду завершения…"
gh run watch "$RUN" --exit-status
