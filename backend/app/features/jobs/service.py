"""Чтение очереди для экрана. Пишет в неё core/jobs.py."""

from datetime import UTC, datetime, timedelta

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import settings
from app.core.jobs import Job

# Верхняя граница жёсткая, как и у журнала аудита, и по той же причине:
# очередь растёт с каждой загрузкой файла и не чистится, а запрос без предела
# однажды выгрузит в память всю её историю.
MAX_LIMIT = 1000
DEFAULT_LIMIT = 100


async def list_jobs(session: AsyncSession, limit: int, actor: str | None) -> list[Job]:
    """Задачи новыми вперёд. actor=None — все (это администратор)."""
    # Второй ключ — id: created_at ставится в коде, и две задачи одной
    # миллисекунды иначе возвращаются в порядке, которого база не обещает.
    # Экран обновляется раз в три секунды, и строки перетасовывались бы сами
    # по себе — человек читает это как новую работу.
    query = select(Job).order_by(Job.created_at.desc(), Job.id).limit(limit)
    if actor is not None:
        query = query.where(Job.actor == actor)
    return list((await session.execute(query)).scalars().all())


async def worker_is_alive(session: AsyncSession) -> bool:
    """Есть ли признаки, что воркер жив.

    Признак — свежая отметка живости у ЛЮБОЙ задачи, в любом состоянии.
    Читается он поэтому не как «процесс воркера существует», а как «очередь
    двигалась не дольше JOB_STALE_AFTER_SECONDS назад».

    Порог взят тот же, что у `claim`, и это не совпадение: очередь считает
    задачу брошенной ровно по нему. Два разных порога означали бы, что экран
    называет живым воркера, у которого очередь уже отбирает задачи.

    Состояние задачи в отборе не участвует НАМЕРЕННО. Воркер, доделавший
    последнюю задачу, среди running отметок не оставляет вовсе: сузь запрос
    до них — и исправный контур объявлялся бы мёртвым в ту же секунду, в
    которую закончил работу, а на экране висело бы «некому взять» при пустой
    очереди.

    Чего признак НЕ ловит, и это стоит знать тому, кто по нему чинит контур:

    - Простаивающий воркер. Пока никто ничего не ставил дольше порога,
      «работает» и «не запущен» неотличимы ничем: воркер, которому нечего
      делать, следов не оставляет. Первая же поставленная задача разницу
      проявляет — и нужна она ровно тогда.
    - Окно ложной тревоги сразу после постановки. Между появлением задачи в
      очереди и её взятием проходит до JOB_POLL_SECONDS, и всё это время на
      исправном контуре признак говорит «не жив». Экран опрашивает его реже,
      чем воркер опрашивает очередь, но совсем этого окна не закрывает.
    - Окно ложного спокойствия после смерти. Воркер, умерший сразу после
      завершения задачи, остаётся «живым» до протухания её отметки — до
      порога, то есть до минуты на умолчаниях.

    Убрать первые два можно было бы только отдельной отметкой самого
    процесса воркера — то есть ещё одной таблицей и ещё одним понятием
    «жив», которое разъехалось бы с тем, которым пользуется claim. Пока
    очередь — единственный источник правды о фоновой работе, признак
    считается по ней.
    """
    fresh_after = datetime.now(UTC) - timedelta(
        seconds=settings.job_stale_after_seconds
    )
    row = await session.execute(
        select(Job.id).where(Job.heartbeat_at > fresh_after).limit(1)
    )
    return row.first() is not None
