"""Файлы на диске контура.

Загруженный файл — ИСХОДНИК. В ночную копию контура попадает база, а не
диск: всё производное — разобранные строки, сводки, обученные модели —
живёт в базе и копируется вместе с ней. Потеря файла означает «загрузить
заново», а не «потерять работу». Это записано в реестре известного долга.
"""

import uuid
from pathlib import Path

from app.core.config import settings
from app.core.errors import RecordNotFound, RuleViolation

# Сигнатура zip: xlsx — это zip с xml внутри.
_ZIP_MAGIC = b"PK\x03\x04"

# Начала форматов, которые таблицей быть не могут. Список короткий и
# закрытый намеренно: он ловит грубую ошибку — «отправил не тот файл», — а
# не пытается быть определителем типов. Последняя строка — старый .xls
# (составной документ OLE): его pandas без отдельного движка не читает, и
# внятный отказ здесь лучше, чем невнятный при разборе.
_NOT_A_TABLE = (
    b"%PDF",
    b"\x89PNG",
    b"\xff\xd8\xff",
    b"GIF8",
    b"\x7fELF",
    b"\x1f\x8b",
    b"\xd0\xcf\x11\xe0",
)

# Сколько байт смотрим. Не восемь: сигнатуру-то и восьми хватит, но нулевой
# байт — вторая половина правила — в первых восьми оказывается редко. У
# формата без известного начала двоичность видна на первых сотнях байт, не
# на первых восьми. И не весь файл: сканировать 32 МиБ ради проверки типа
# значит тратить ровно ту память, которую бережёт потолок.
_HEAD_BYTES = 4096


def _dir() -> Path:
    # Каталог создаётся при первом обращении, а не при старте: на контуре
    # его не заводит провижинер, а падать на старте из-за отсутствующего
    # каталога загрузок значит не пускать в приложение тех, кому файлы не
    # нужны вовсе.
    settings.upload_dir.mkdir(parents=True, exist_ok=True)
    return settings.upload_dir


def path_for(file_id: uuid.UUID) -> Path:
    # Имя строится ИЗ идентификатора, а не из загруженного имени. Никакой
    # склейки с пользовательской строкой здесь нет и быть не должно: файл,
    # названный «../../.env», иначе становится путём.
    return _dir() / str(file_id)


def human_size(size_bytes: int) -> str:
    """Размер словами, которые человек прочитает.

    Целочисленное деление на мегабайты врало на любом пределе меньше
    мегабайта: `UPLOAD_MAX_BYTES=1000000` давало отказ «Файл больше
    предельного (0 МиБ)» — то есть предел, который невозможно соблюсти.
    А предел меньше мегабайта — не выдумка: на контуре его задают под
    `client_max_body_size` в nginx, и там умолчание ровно 1 МиБ.
    """
    if size_bytes >= 1024 * 1024:
        mib = size_bytes / 1024 / 1024
        # Дробная часть только когда она есть: «32 МиБ» читается лучше, чем
        # «32.0 МиБ», а «1.5 МиБ» лучше, чем «1 МиБ» о полутора.
        return f"{mib:.0f} МиБ" if mib == int(mib) else f"{mib:.1f} МиБ"
    return f"{size_bytes / 1024:.0f} КиБ"


def _refuse_if_over_limit(size: int) -> None:
    """Общий отказ по объёму для обеих проверок ниже.

    Текст один, потому что человеку это одна и та же причина отказа: он не
    должен по формулировке догадываться, на какой из двух линий его
    остановили. Сами проверки при этом остаются раздельными — каждая
    закрывает свой обход потолка.
    """
    if size > settings.upload_max_bytes:
        raise RuleViolation(
            f"Файл больше предельного ({human_size(settings.upload_max_bytes)})",
            field="file",
        )


def check_size(declared: int | None) -> None:
    """Отказ по объявленному размеру — до чтения тела."""
    if declared is not None:
        _refuse_if_over_limit(declared)


def detect_kind(head: bytes) -> str:
    """Тип по содержимому, а не по расширению.

    «отчёт.csv» с телом PDF иначе доходит до pandas и падает там сообщением
    про кодировку — человек читает его и ищет причину в своей таблице.

    Здесь отделяют ТАБЛИЦУ ОТ ДВОИЧНОГО, а не одну кодировку от другой.
    Разница существенная: проверка «декодируется ли голова как utf-8»
    отвергала бы обычный CSV в cp1251 — то, чем Excel выгружает по
    умолчанию, — сообщением «Не CSV и не XLSX». А `domain/tables.py` cp1251
    читает намеренно и с отдельной проверкой на это. То есть загрузка
    отказывала бы в файле, который разбор умеет читать, и два слоя
    противоречили бы друг другу.

    Поэтому кодировка — забота разбора, а не загрузки. Здесь ловится только
    грубое: известное начало не-таблицы и нулевой байт, которого в тексте не
    бывает.
    """
    if head.startswith(_ZIP_MAGIC):
        return "xlsx"
    if head.startswith(_NOT_A_TABLE) or b"\x00" in head:
        raise RuleViolation("Не CSV и не XLSX", field="file")
    return "csv"


def save(data: bytes) -> uuid.UUID:
    """Кладёт байты на диск и возвращает идентификатор.

    Размер проверяется ещё раз, уже по факту: Content-Length клиент может не
    прислать или соврать, и без второй проверки потолок обходится одним
    отсутствующим заголовком.
    """
    _refuse_if_over_limit(len(data))
    detect_kind(data[:_HEAD_BYTES])
    file_id = uuid.uuid7()
    path_for(file_id).write_bytes(data)
    return file_id


def read(file_id: uuid.UUID) -> bytes:
    path = path_for(file_id)
    if not path.is_file():
        # Файл мог не пережить переезд контура или чистку диска, а строка о
        # нём в базе есть. Это «нет», а не пятисотка: у отсутствия исходника
        # есть понятный человеку смысл.
        raise RecordNotFound("Файл не найден на диске")
    return path.read_bytes()


def delete(file_id: uuid.UUID) -> None:
    # missing_ok: удаление зовут при откате загрузки, и файла к тому моменту
    # может не быть. Падать здесь значит превращать уборку в новую ошибку.
    path_for(file_id).unlink(missing_ok=True)
